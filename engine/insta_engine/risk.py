"""风控（反自动化验证）识别——**单一来源**，供判定脚本、失败样本回流、报告共用。

为什么单独成模块：这个特征集**至少有两处消费方**（跑分判定 + 失败样本回流），
各存一份必然漂移——而漂移的后果是"同一轮失败，一处算风控、一处算产品缺陷"，
正好是 要避免的那个**反向结论**。

**策略边界（红线）**：本模块**只识别、只报出**，不提供任何绕过手段
（滑块破解 / 验证码识别 / IP 池 / 改机）。理由：
① 被贴"爬虫工具"标签后用户反而不敢用；② 法律风险需法务确认；③ 技术上是无底洞。

**为什么用一组关键词而不是单一字符串**：实测两天内就见到两种形态——
滑块拼图（「请拖动下方滑块完成拼图」）与图片点选（「身份核实 / 请依次点击下图图标」）。
风控形态会变，单字符串必然漏报。
"""

from __future__ import annotations

#: 风控页的特征文案。**只增不减**：删掉一条 = 那类风控会被算成产品缺陷。
RISK_MARKERS = ("拖动下方滑块", "完成拼图", "身份核实", "请依次点击下图图标",
                "安全验证", "验证码", "行为验证")


def detect_in_text(text: str) -> str | None:
    """在任意文本（dump / 报错 / warning）里找风控特征。命中返回该特征，否则 None。"""
    t = text or ""
    return next((m for m in RISK_MARKERS if m in t), None)


def detect_in_xml(xml: str) -> str | None:
    """在 uiautomator dump 里找风控特征。语义同 `detect_in_text`（dump 也是文本）。

    单独留这个函数名是为了**让调用点自解释**：看到 `detect_in_xml` 就知道传的是 dump，
    看到 `detect_in_text` 就知道传的是日志/报错。
    """
    return detect_in_text(xml)


# ---------------------------------------------------------------------------
# 下面是**探索**用的口径：同一个"风控"概念，但**两个消费方的取舍相反**
# ---------------------------------------------------------------------------
#
# | 消费方 | 问的问题 | 漏报的代价 | 误报的代价 | 所以 |
# |---|---|---|---|---|
# | 判定脚本（`RISK_MARKERS`） | 这一轮任务是不是被 App 拦了？ | **把风控算成产品缺陷**（反向结论） | 把真失败排除出分母 | **宁可多报** |
# | 探索（`RISK_STRONG`） | 这一页值不值得**立即终止本轮**？ | 继续空转 12 次回退 | **白白砍掉一轮探索** | **宁可少报** |
#
# ⚠️ 所以两组特征**故意不同**，不是重复定义。改任意一组前先看这张表。

#: 探索用**强特征**：只出现在风控/验证页上的文案，命中即判。
RISK_STRONG = ("拖动下方滑块", "滑动滑块", "滑块验证", "完成拼图", "拖动箭头",
               "身份核实", "请依次点击下图图标", "行为验证", "安全验证")

#: 探索用**弱特征**：正常登录/帮助流程里也会出现，**单独出现不算**。
#: 实测反例（2026-10-07）：某 App「登录帮助」页有「收不到验证码」，
#: 只按关键词判会把一个**正常页面**误判成风控 ⇒ 白砍一轮探索。
#: 保留这个元组是为了**把"我们知道但不能单独用"的词显式记下来**（防止有人顺手加进 RISK_STRONG）。
RISK_WEAK = ("验证码", "图形验证", "语音验证")

#: activity 名里的风控线索——**辅助判据**。
#: ⚠️ 不能单独作准：某 App 的验证码页 activity 是 `LoginActivity`（没有任何线索）。
#: 但对**专用风控页**有效，而且实测它们可能**一个文案都没有**
#: （`YodaRouterTransparentActivity`：1 个节点、0 条文案）。
RISK_ACTIVITY_HINTS = ("riskhandle", "yoda", "captcha", "verifyactivity", "securitycheck")


def detect_risk_page(activity: str, xml: str) -> str | None:
    """**探索用**的风控页判定。命中返回可读的命中依据（写进报告），否则 None。

    判据（**precision 优先**——误报会白砍一轮探索）：
    1. `RISK_STRONG` 任一命中；或
    2. `activity` 名命中 `RISK_ACTIVITY_HINTS`。

    `RISK_WEAK` **单独出现不算**（正常登录流程里到处都是「验证码」）。
    """
    hit = next((m for m in RISK_STRONG if m in (xml or "")), None)
    if hit:
        return hit
    act = (activity or "").lower()
    hint = next((h for h in RISK_ACTIVITY_HINTS if h in act), None)
    return f"activity:{hint}" if hint else None
